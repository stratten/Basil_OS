def _local_generation(
    max_output: int,
    *,
    reasoning_mode: str = "tagged",
    activity_analysis: Optional[int] = None,
    agent_execution: Optional[int] = None,
    final_synthesis: Optional[int] = None,
    sampling: Optional[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    return {
        "reasoning_mode": reasoning_mode,
        "sampling": sampling
        or {
            "temperature": 0.1,
            "top_p": 0.95,
            "top_k": 40,
            "min_p": None,
            "repeat_penalty": 1.15,
        },
        "output_budgets": {
            "decision": min(512, max_output),
            "structured": min(2048, max_output),
            "narrative": min(2048, max_output),
            "activity_analysis": activity_analysis if activity_analysis is not None else min(4096, max_output),
            "general": min(4096, max_output),
            "agent_execution": agent_execution if agent_execution is not None else max_output,
            "final_synthesis": final_synthesis if final_synthesis is not None else max_output,
        },
    }


