from fastapi import APIRouter, HTTPException
from pydantic import BaseModel
from typing import Optional
import logging
from pathlib import Path
import time

from api.services.capture.shared.window_capture_bridge import (
    deliver_capture_response,
    request_swift_window_capture,
)

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/capture", tags=["capture"])

# Response Models
class CaptureResultResponse(BaseModel):
    """Response model for capture operations."""
    success: bool
    message: Optional[str] = None
    image_path: Optional[str] = None
    app_name: Optional[str] = None
    window_title: Optional[str] = None
    timestamp: Optional[int] = None  # Unix milliseconds, generated by Swift client
    capture_method: Optional[str] = None
    has_image: Optional[bool] = None
    timeout_duration: Optional[float] = None

class CaptureResponseAckResponse(BaseModel):
    """Response model for capture response acknowledgment."""
    status: str
    message: str

