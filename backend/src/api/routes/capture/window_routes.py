@router.post("/swift-window-immediate", response_model=CaptureResultResponse)
async def trigger_swift_window_capture_immediate() -> CaptureResultResponse:
    """
    Trigger Swift WindowCaptureService to capture the current active window via WebSocket.
    
    This endpoint sends a WebSocket message to the frontend requesting an immediate capture,
    then waits for the frontend to respond with the capture results.
    
    Returns:
        JSON response with capture results including file path
    """
    result = await request_swift_window_capture("agent_task")
    return CaptureResultResponse(**result)

@router.post("/capture-response", response_model=CaptureResponseAckResponse)
async def handle_capture_response(response_data: dict) -> CaptureResponseAckResponse:
    """
    Handle capture response from the frontend Swift app.
    
    This endpoint receives the results of a capture request that was sent via WebSocket.
    """
    try:
        deliver_capture_response(response_data)
        return CaptureResponseAckResponse(
            status="success",
            message="Capture response received"
        )
        
    except Exception as e:
        logger.error(f"❌ Error handling capture response: {e}")
        raise HTTPException(status_code=500, detail=f"Error handling capture response: {str(e)}")
